package main

import "time"

// realChainWait 是 `cmd/dshd` 里**真进程用例**等待"某件事发生了"的统一预算。
//
// # 为什么要有这个常量
//
// 这些用例不是单测：它们起**真 dshd 子进程**、真的建 home、真的绑端口、真的跑一轮
// prompt，然后等一个信号（模型请求到达、作业自然退出、side query 返回……）。
// 原先各处散落着 `10s` / `15s` 字面量，那是**按快机器估的**。
//
// CI runner 只有 2 核，还套着 `-race`（二进制更慢）。实测同一用例：
// 本地 race 约 6.8s，CI 上 16.0s —— **慢 2.4 倍**，15s 的预算必然间歇性不够。
//
// 2026-11-13 一天之内，这一处问题**红了三次**，而且是三条不同的用例
// （`TestSettingsFormRealDSHD…` 两次、`TestModelCatalogRealDSHD…` 一次）：
// 每次单独修一条，下次红另一条 —— 典型的打地鼠。
// 所以改成**一个常量管全部 15 处**，要调只调这里。
//
// # 它不降低任何断言强度
//
// **超时是环境容差，不是行为契约**：放宽它只是给慢机器更多时间，
// 事件没发生照样 fail-closed；"等到了但内容不对"的断言一条都没动。
const realChainWait = 60 * time.Second
